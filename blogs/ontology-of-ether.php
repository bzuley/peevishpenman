      <h2>A Creation Story</h2>

      <p>I wrote this in 2015, imagining survivors gathered around a fire, trying to explain the world they had lost.</p>

      <p>Before the beginning, there was nothing. Space and time lacked dimension. Consequently, there was no matter, and that mattered to no one, because there was no one there to observe it.</p>

      <p>And the nothing was the great mystery, which, in its mystery, divided into the animate and inanimate: that which had the power to observe itself and the part of itself that was to be observed.</p>

      <p>And it was aware of itself as something that had caused itself to come into being. And it knew causality. It knew time. There was now a before and after within its observation of itself.</p>

      <p>And in the process of observing these new elements, it drew in what was observed and released what was doing the observing into that which was being observed. And it knew this relationship to itself as motion. And it knew space through this motion.</p>

      <p>And the new motions gathered energy, which increased through space and time. And the great mystery was repelled and attracted to what it knew as that which was moving and that which was not moving. And it knew matter, and it had mass.</p>

      <p>And the separate parts of the great mystery continued to factor into more parts. Though knowing before and after, the great mystery also knew them as having been one whole. With each division, it observed the process of separation and previous combination in its memory, an observation of before. And it recognized the parts did not equal more or less than before. And they usually took the shortest distance in space, moving away from each other.</p>

      <p>But the great mystery was attracted to the memory of its original form and repelled by the constant motion of its own parts. And the repulsion became a will, and the will was a force of fear. The observer focused its will on the before, and the parts of the great mystery that were matter pulled back together.</p>

      <p>And it exploded. And it knew gravity and emotion.</p>

      <p>And with its new will, the great mystery was immediately attracted to itself. It designated itself divine and all other things profane. And observing inward, it experienced fear at that which was not divine. And the will of the great mystery, in its great fear, exploded.</p>

      <p>And the new parts of the observer began to observe independently as the motion of the energy separated them, and the new gravity and emotions of the new wills drew them together in love until tiny bits of observation and matter reformed as consciousnesses. And there was life.</p>

      <p>And the new forms of life began to observe their environment, to unitize and name the plethora of parts that had once been the great mystery, in processes called language and math.</p>

      <p>Matter flowed through the consciousnesses of life, and those consciousnesses were drawn together and pushed apart, separately and infinitely through space-time, developing incredible complexities. But no consciousness could observe the whole, being only a part of the whole. But they were attracted to other parts, and with their will, they began to selectively reproduce.</p>

      <p>And the parts that were life began to perceive themselves and were repulsed by their separation from the whole. And they expanded their observation into space or time and their own nature, attracted to the nature of the whole that surrounded them. But as they observed more and more of the whole, their own consciousness lost cohesion.</p>

      <p>And through a process of symbolic representation, the powerful observers began to simplify the impossible awareness of the whole of the great mystery. They made themselves stronger with increasingly complex symbols in art, math and language. And among these life forms were humans.</p>

      <p>And so it was natural for humans to be attracted and repulsed by the symbols of the other humans, as they resembled the whole of the great mystery that was both attracted and repulsed by itself and the process that brought it all into being.</p>

      <p>And it was natural for humans to turn their symbolic representations on all the mysteries they could observe in their environment and within themselves. And the humans knew the philosophies, the arts and the sciences.</p>

      <p>And the moderns made the technologies to control their environment and each other out of fear and attraction to the symbols. And with the technologies, they observed the nature of the universe farther and farther until humanity itself developed a collective consciousness called history, and then they lost cohesion and exploded, which was known as the apocalypse.</p>

      <p>What remained of the moderns drew together in self-preservation with an awareness of the rudimentary principles of universal pulsation.</p>

      <p>And never again would they tempt the forces of nature by thinking too deeply about anything.</p>

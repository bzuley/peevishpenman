      <h2>Stage Two: Getting Feedback</h2>

      <p>
        Search strategies for finding a writing group in your area are simple using Boolean Language and other
        librarian approved search methods. Most importantly, search by key words or phrases. Do not enter a full
        question into a search engine. Use "Writing Group" AND "Wellington New Zealand" rather than "Where can I
        find a Writing Group in Wellington New Zealand?"
      </p>

      <p>
        <strong>First</strong>, you want to search sites that talk about writing groups and not sites that contain
        both the word writing and groups. Use quotations to locate the exact phrase within websites.
        Ex: <code>"Writing Groups"</code>
      </p>

      <p>
        <strong>Second</strong>, a writing group can be called different names such as a critique group or a
        writing circle. Search for every variation using the Boolean operator "OR." Place "OR" between phrases to
        include all variations in your search.
        Ex: <code>"Writing Group" OR "Critique Group" OR "Writing Circle" OR "Writer's Society"</code>
      </p>

      <p>
        <strong>Third</strong>, a word such as writer can be truncated with the "*" to produce results containing
        all variations such as writer, writing, writers, written, write... By replacing the letters that vary
        between words, all similar variations can be retrieved from a search engine. Ex: <code>writ*</code>
      </p>

      <p>
        <strong>Finally</strong>, add the name of your town, county, province, city, region, suburb using the same
        methods. When you contact the group, let them know how you found them and why you want to join. The groups
        vary as much as writers themselves and while one may not be the most productive environment for you or
        your style, there are others. If you live rurally or cannot make the commitment to meeting with a writing
        group, there are also online communities of writers.
      </p>

      <p>
        Are there other ways? Yes, one of the Peevish Penman editors actually found her first writing group through
        the Nanowrimo website.
      </p>


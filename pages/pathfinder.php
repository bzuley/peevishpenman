      <h2>Stage Three: In Print</h2>

      <p>Unless you're just writing for fun, you're going to want to sell your work, so you should write to sell.</p>

      <p>
        As soon as money is involved, there will be people willing to scam for it, but it's easier to avoid them
        than you might think. Don't trust anything that looks too good to be true. And keep reminding yourself, if
        all we had to do as writers was give the right organization a hundred dollars to promote us and we'd be an
        instant bestseller, why wouldn't everyone do it? And don't quit your day job just yet.
      </p>

      <p>Good rules to follow:</p>
      <ul>
        <li>Do not pay an agent for representation</li>
        <li>Do not pay a publisher to produce your book</li>
        <li>Read other writer's reviews of an organization's "author services" before buying</li>
      </ul>

      <p>
        However, with that said, don't be so skeptical that you miss real opportunities either. A good business
        plan is essential for all authors whether they go the traditional route or self-publish and advertising and
        marketing techniques work. Stick to a budget that you can afford and never give up!
      </p>

